float SampFontRenderer::get_char_width_samp(int font_id, char c, float letter_w, bool proportional) const {
    if (font_id < 0 || font_id > 3) font_id = 1;
    if (c == '_') c = ' '; // In GTA SA / SA-MP, underscore is displayed as space!
    uint8_t uc = static_cast<uint8_t>(c);
    if (uc < 32 || uc > 126) uc = 32;
    int idx = uc - 32;
    const auto& g = s_fonts[font_id].glyphs[idx];
    if (proportional) {
        return g.advance * letter_w * 0.95f;
    } else {
        return s_fonts[font_id].unprop * letter_w * 0.95f;
    }
}

float SampFontRenderer::get_space_width_samp(int font_id, float letter_w, bool proportional) const {
    return get_char_width_samp(font_id, ' ', letter_w, proportional);
}

ImVec2 SampFontRenderer::measure_text_samp(
    int font_id,
    const std::string& text,
    float letter_w,
    float letter_h,
    bool proportional
) {
    if (font_id < 0 || font_id > 3) font_id = 1;
    auto spans = SampColorParser::parse(text, 0xFFFFFFFF);
    
    float max_line_w = 0.0f;
    float current_line_w = 0.0f;
    int line_count = 1;

    for (const auto& span : spans) {
        if (span.is_newline) {
            max_line_w = std::max(max_line_w, current_line_w);
            current_line_w = 0.0f;
            line_count++;
            continue;
        }
        for (char c : span.text) {
            current_line_w += get_char_width_samp(font_id, c, letter_w, proportional);
        }
    }
    max_line_w = std::max(max_line_w, current_line_w);
    
    float line_h = letter_h * 10.5f;
    float total_h = static_cast<float>(line_count) * line_h;
    return ImVec2(max_line_w, total_h);
}

void SampFontRenderer::render_textdraw(
    int font_id,
    const std::string& text,
    float samp_x,
    float samp_y,
    float letter_w,
    float letter_h,
    uint32_t text_color,
    uint32_t bg_color,
    int shadow,
    int outline,
    bool proportional,
    TextDrawAlignment alignment,
    const Viewport& viewport,
    ImDrawList* draw_list
) {
    if (!draw_list || text.empty()) return;
    if (font_id < 0 || font_id > 3) font_id = 1;
    
    GLuint tex = (font_id == 0 || font_id == 2)
        ? AssetManager::get().font2_texture
        : AssetManager::get().font1_texture;
        
    if (tex == 0) return;
    
    float unprop = s_fonts[font_id].unprop;
    
    // Parse SA-MP formatting tags (~r~, ~g~, ~b~, etc.)
    auto spans = SampColorParser::parse(text, text_color);
    
    // Group spans by lines
    std::vector<std::vector<TextSpan>> lines;
    std::vector<TextSpan> cur_line;
    for (const auto& span : spans) {
        if (span.is_newline) {
            lines.push_back(cur_line);
            cur_line.clear();
        } else if (!span.text.empty()) {
            cur_line.push_back(span);
        }
    }
    lines.push_back(cur_line);
    
    float line_spacing_samp = letter_h * 10.5f;
    float scale_x = letter_w * 0.95f;
    float scale_y = letter_h * 0.60f;
    
    auto draw_line = [&](const std::vector<TextSpan>& line, float start_x, float start_y, uint32_t override_color, bool use_override) {
        float cur_x = start_x;
        
        for (const auto& span : line) {
            uint32_t c = use_override ? override_color : span.color;
            ImU32 im_col = IM_COL32((c >> 24) & 0xFF, (c >> 16) & 0xFF, (c >> 8) & 0xFF, c & 0xFF);
            
            for (char ch : span.text) {
                if (ch == '_') ch = ' '; // In GTA SA / SA-MP, underscore is displayed as space!
                uint8_t uc = static_cast<uint8_t>(ch);
                if (uc < 32 || uc > 126) uc = 32;
                int idx = uc - 32;
                const auto& g = s_fonts[font_id].glyphs[idx];
                
                if (uc == 32 || g.w <= 0.0f) {
                    cur_x += (proportional ? g.advance : unprop) * scale_x;
                    continue;
                }
                
                float gw_samp = g.w * scale_x;
                float gh_samp = g.h * scale_y;
                float gy_samp = start_y + g.y_off * scale_y;
                
                float gx_samp = cur_x;
                if (!proportional) {
                    float cell_w_samp = unprop * scale_x;
                    gx_samp = cur_x + (cell_w_samp - gw_samp) * 0.5f;
                }
                
                float p1_x, p1_y;
                viewport.samp_to_screen(gx_samp, gy_samp, p1_x, p1_y);
                float p2_x = p1_x + viewport.samp_to_screen_scale_x(gw_samp);
                float p2_y = p1_y + viewport.samp_to_screen_scale_y(gh_samp);
                
                draw_list->AddImage(
                    (ImTextureID)(intptr_t)tex,
                    ImVec2(p1_x, p1_y),
                    ImVec2(p2_x, p2_y),
                    ImVec2(g.u1, g.v1),
                    ImVec2(g.u2, g.v2),
                    im_col
                );
                
                cur_x += (proportional ? g.advance : unprop) * scale_x;
            }
        }
    };
    
    float cur_samp_y = samp_y;
    
    for (const auto& line : lines) {
        float line_w_samp = 0.0f;
        for (const auto& span : line) {
            for (char ch : span.text) {
                line_w_samp += get_char_width_samp(font_id, ch, letter_w, proportional);
            }
        }
        
        float line_start_x = samp_x;
        if (alignment == TextDrawAlignment::CENTER) {
            line_start_x = samp_x - line_w_samp * 0.5f;
        } else if (alignment == TextDrawAlignment::RIGHT) {
            line_start_x = samp_x - line_w_samp;
        }
        
        // 1. Outline pass
        if (outline > 0) {
            float o_samp = static_cast<float>(outline) * 0.8f;
            draw_line(line, line_start_x - o_samp, cur_samp_y, bg_color, true);
            draw_line(line, line_start_x + o_samp, cur_samp_y, bg_color, true);
            draw_line(line, line_start_x, cur_samp_y - o_samp, bg_color, true);
            draw_line(line, line_start_x, cur_samp_y + o_samp, bg_color, true);
            if (outline > 1) {
                draw_line(line, line_start_x - o_samp, cur_samp_y - o_samp, bg_color, true);
                draw_line(line, line_start_x + o_samp, cur_samp_y - o_samp, bg_color, true);
                draw_line(line, line_start_x - o_samp, cur_samp_y + o_samp, bg_color, true);
                draw_line(line, line_start_x + o_samp, cur_samp_y + o_samp, bg_color, true);
            }
        }
        // 2. Shadow pass
        else if (shadow > 0) {
            float s_samp = static_cast<float>(shadow) * 0.9f;
            draw_line(line, line_start_x + s_samp, cur_samp_y + s_samp, bg_color, true);
        }
        
        // 3. Main text pass
        draw_line(line, line_start_x, cur_samp_y, 0, false);
        
        cur_samp_y += line_spacing_samp;
    }
}
